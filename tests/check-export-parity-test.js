const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const { compareEvidence } = require('./check-export-parity.js');
const messages = [{ role: 'user', text: 'question' }, { role: 'assistant', text: 'answer\n    code indent' }];
const capture = () => ({ conversation: 'synthetic-chat', branch: 'selected', complete: true, messages: structuredClone(messages), references: [], process: [] });
const evidence = provider => ({ provider, api: capture(), normal: capture(), dom: capture() });
for (const provider of ['chatgpt', 'gemini', 'grok', 'claude']) {
    const result = compareEvidence(evidence(provider));
    assert.equal(result.bodyPassed, true);
    assert.equal(result.body.status, 'match');
}
const changedText = evidence('chatgpt');
changedText.api.messages[1].text = 'answer\ncode indent';
assert.deepEqual(compareEvidence(changedText).body.differences[0].mismatches, [2]);
const role = evidence('gemini');
role.normal.messages[1].role = 'user';
assert.equal(compareEvidence(role).bodyPassed, false);
const order = evidence('grok');
order.api.messages.reverse();
assert.equal(compareEvidence(order).bodyPassed, false);
const omitted = evidence('chatgpt');
omitted.normal.messages.pop();
assert.equal(compareEvidence(omitted).body.differences[0].mismatches[0], 2);
const duplicate = evidence('chatgpt');
duplicate.api.messages.push(duplicate.api.messages[1]);
assert.equal(compareEvidence(duplicate).body.differences[0].mismatches[0], 3);
const partial = evidence('chatgpt');
partial.dom.complete = false;
assert.throws(() => compareEvidence(partial));
const missing = evidence('chatgpt');
delete missing.normal;
assert.throws(() => compareEvidence(missing));
const claude = evidence('claude');
delete claude.normal;
assert.equal(compareEvidence(claude).bodyPassed, true);
const empty = evidence('claude');
empty.api.messages = [];
assert.throws(() => compareEvidence(empty));
const branch = evidence('claude');
branch.api.branch = 'other';
assert.throws(() => compareEvidence(branch));
const equivalent = evidence('chatgpt');
equivalent.api.messages[1].text = ' answer\r\n    code\u00a0indent\n';
assert.equal(compareEvidence(equivalent).bodyPassed, true);
const refs = evidence('chatgpt');
refs.api.references = [{ messageIndex: 2, label: 'source', url: 'https://example.test' }];
assert.equal(compareEvidence(refs).bodyPassed, true);
assert.equal(compareEvidence(refs).references.status, 'different');
const progress = evidence('gemini');
progress.normal.process = [{ messageIndex: 2, text: 'Searching', evidence: 'visible tool indicator' }];
assert.equal(compareEvidence(progress).bodyPassed, true);
assert.equal(compareEvidence(progress).process.status, 'different');
const unknown = evidence('chatgpt');
unknown.api.references = null;
assert.equal(compareEvidence(unknown).references.status, 'unverified');
const invalidIndex = evidence('chatgpt');
invalidIndex.api.references = [{ messageIndex: 3, label: 'source', url: 'https://example.test' }];
assert.throws(() => compareEvidence(invalidIndex));
const invalidEvidence = evidence('chatgpt');
invalidEvidence.api.process = [{ messageIndex: 1, text: 'hidden', evidence: '' }];
assert.throws(() => compareEvidence(invalidEvidence));
const cli = data => spawnSync(process.execPath, [path.join(__dirname, 'check-export-parity.js'), '-'], { input: JSON.stringify(data), encoding: 'utf8' });
assert.equal(cli(evidence('chatgpt')).status, 0);
assert.equal(cli(changedText).status, 1);
assert.equal(cli(partial).status, 2);
assert(!cli(changedText).stdout.includes('question'));
assert(!cli(refs).stdout.includes('https://example.test'));
console.log('ok export parity: body grades, annotation advisories, validation and private CLI output');
